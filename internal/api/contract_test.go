// TestOpenAPIContractMatchesRoutes is what makes the comment in routes() true:
// an endpoint added to the router without a matching entry in
// openapi/panel.yaml fails the build. The router is the executable truth; the
// spec is the generated TS client's input and the reviewer's checklist, and the
// two are not allowed to drift.
func TestOpenAPIContractMatchesRoutes(t *testing.T) {
	cfg := &config.Config{
		Bind: "127.0.0.1", Port: 29080, Entrance: testEntrance, TLS: true,
		DataDir: t.TempDir(), LogDir: t.TempDir(),
		SessionTTL: config.Duration(time.Hour), LoginLimit: 5, UnauthStatus: 404,
	}
	s := &Server{Cfg: cfg}
	routes := map[string]bool{}
	err := chi.Walk(s.routes(), func(method, pattern string, _ http.Handler, _ ...func(http.Handler) http.Handler) error {
		// The UI catch-all and the entrance page are not API surface.
		if pattern == "/*" || pattern == cfg.Entrance {
			return nil
		}
		routes[method+" "+pattern] = true
		return nil
	})
	if err != nil {
		t.Fatalf("chi.Walk: %v", err)
	}
	if len(routes) == 0 {
		t.Fatal("walk found no routes")
	}

	spec := specOperations(t, filepath.Join("openapi", "panel.yaml"))
	var missing, extra []string
	for r := range routes {
		if !spec[r] {
			missing = append(missing, r)
		}
	}
	for r := range spec {
		if !routes[r] {
			extra = append(extra, r)
		}
	}
	sort.Strings(missing)
	sort.Strings(extra)
	if len(missing) > 0 {
		t.Errorf("接口已注册但未写入 openapi/panel.yaml：%s", strings.Join(missing, ", "))
	}
	if len(extra) > 0 {
		t.Errorf("openapi/panel.yaml 描述了不存在的接口：%s", strings.Join(extra, ", "))
	}
}

// TestSpecDeclaresTheSecurityContract keeps the documented security model tied
// to the implementation: rename a cookie or drop the CSRF scheme and this fails.
func TestSpecDeclaresTheSecurityContract(t *testing.T) {
	b := readSpec(t)
	for _, want := range []string{
		"name: mp_session",
		"name: X-Mini-CSRF",
		"panel.ip_allowlist",
		"panel.unauth_status",
	} {
		if !strings.Contains(b, want) {
			t.Errorf("规格中缺少 %q", want)
		}
	}
	// There is no reflection-style endpoint: no path takes a module or method
	// name from the request.
	for _, bad := range []string{"mod_name", "class", "action}", "{module}", "{action}"} {
		if strings.Contains(b, bad) {
			t.Errorf("规格里出现反射式接口片段 %q", bad)
		}
	}
	// The only path parameter allowed anywhere is the whitelisted settings key.
	// A free-form module/action segment is how a reflection endpoint (and then a
	// traversal or an RCE) gets written.
	for _, line := range strings.Split(b, "\n") {
		trimmed := strings.TrimSuffix(strings.TrimSpace(line), ":")
		if !strings.HasPrefix(trimmed, "/api/") || !strings.Contains(trimmed, "{") {
			continue
		}
		for _, seg := range strings.Split(trimmed, "/")[1:] {
			if !strings.HasPrefix(seg, "{") {
				continue
			}
			name := strings.Trim(seg, "{}")
			if name != "key" {
				t.Errorf("接口 %s 含非白名单路径参数 {%s}", trimmed, name)
			}
		}
	}
}

// specOperations extracts "METHOD /path" pairs from the paths: block. The parser
// is deliberately line-based: the file's layout is generated by us and checked
// here, which is cheaper than pulling a YAML dependency into a test-only path.
func specOperations(t *testing.T, path string) map[string]bool {
	t.Helper()
	f, err := os.Open(path)
	if err != nil {
		t.Fatalf("open %s: %v", path, err)
	}
	defer f.Close()
	out := map[string]bool{}
	inPaths := false
	var current string
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, "paths:") {
			inPaths = true
			continue
		}
		if !inPaths {
			continue
		}
		// A top-level key at column 0 ends the paths block.
		if len(line) > 0 && !strings.HasPrefix(line, " ") && !strings.HasPrefix(line, "#") {
			break
		}
		if strings.HasPrefix(line, "  ") && !strings.HasPrefix(line, "   ") && strings.HasSuffix(line, ":") {
			current = strings.TrimSuffix(strings.TrimSpace(line), ":")
			continue
		}
		if current == "" {
			continue
		}
		if strings.HasPrefix(line, "    ") && !strings.HasPrefix(line, "     ") {
			key := strings.TrimSuffix(strings.TrimSpace(line), ":")
			switch strings.ToLower(key) {
			case "get", "post", "put", "patch", "delete":
				out[strings.ToUpper(key)+" "+current] = true
			}
		}
	}
	if err := sc.Err(); err != nil {
		t.Fatal(err)
	}
	if len(out) == 0 {
		t.Fatal("spec declares no operations")
	}
	return out
}

func readSpec(t *testing.T) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join("openapi", "panel.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}
